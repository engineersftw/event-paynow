#!/usr/bin/env python3
"""Generates src/sgqr/font-atlas.ts: an anti-aliased glyph atlas for the QR image text.

The Worker cannot rasterise fonts, so printable ASCII (0x20-0x7E) is pre-rendered here from
DejaVu Sans (free licence, https://dejavu-fonts.github.io/License.html) at one pixel size, as
8-bit coverage bitmaps plus per-glyph metrics. Run rarely; the committed output is the source
of truth.

Requires: Python 3 with Pillow (FreeType) and the DejaVu Sans TTF.
Usage:    python3 scripts/generate-font.py [path/to/DejaVuSans.ttf] [pixel-size]
"""
import base64
import sys

from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
SIZE = int(sys.argv[2]) if len(sys.argv) > 2 else 22
font = ImageFont.truetype(TTF, SIZE)
ascent, descent = font.getmetrics()

metrics = []  # [advance*16, width, height, xoff, yoff, dataOffset]
data = bytearray()
for code in range(0x20, 0x7F):
    ch = chr(code)
    adv16 = round(font.getlength(ch) * 16)
    pad = SIZE
    canvas = Image.new('L', (SIZE * 3, SIZE * 3), 0)
    ImageDraw.Draw(canvas).text((pad, pad + ascent), ch, font=font, fill=255, anchor='ls')
    box = canvas.getbbox()
    if box is None:  # space
        metrics.append([adv16, 0, 0, 0, 0, len(data)])
        continue
    glyph = canvas.crop(box)
    metrics.append([adv16, glyph.width, glyph.height, box[0] - pad, box[1] - (pad + ascent), len(data)])
    data.extend(glyph.tobytes())

rows = ',\n  '.join(', '.join(str(v) for v in m).join('[]') for m in metrics)
open('src/sgqr/font-atlas.ts', 'w').write(f"""/**
 * Anti-aliased glyph atlas for the QR image text (printable ASCII 0x20-0x7E).
 *
 * Auto-generated by `python3 scripts/generate-font.py` from DejaVu Sans at {SIZE}px; do not edit.
 * Each GLYPHS row is [advance (1/16 px), width, height, xOffset, yOffset (from the baseline), offset
 * into the coverage bytes]; the coverage is 8-bit, row-major, base64.
 */

export const FONT_ASCENT = {ascent};
export const FONT_DESCENT = {descent};

/** First character code in GLYPHS. */
export const FONT_FIRST = 0x20;

export const GLYPHS: number[][] = [
  {rows},
];

const COVERAGE_BASE64 =
  '{base64.b64encode(bytes(data)).decode()}';

export const COVERAGE: Uint8Array = Uint8Array.from(atob(COVERAGE_BASE64), (c) => c.charCodeAt(0));
""")
print('glyphs', len(metrics), 'bytes', len(data), 'ascent/descent', ascent, descent)
