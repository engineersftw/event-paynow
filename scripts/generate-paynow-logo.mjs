// Generates src/sgqr/paynow-logo.ts from the PayNow brand PNG asset.
//
// The PayNow logo is a single-color (crimson) wordmark + "$" glyph on a
// transparent background, so we store it as a 1-bit alpha mask (row-major,
// packed MSB-first into bytes) plus one RGB color. That keeps the embedded
// asset tiny and runtime-agnostic (no zlib, no PNG decode in the isolate).
//
// Usage:
//   node scripts/generate-paynow-logo.mjs <path-to-logo.png>
//
// Output is written to src/sgqr/paynow-logo.ts.
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/generate-paynow-logo.mjs <path-to-logo.png>');
  process.exit(1);
}

const png = PNG.sync.read(readFileSync(src));

// Trim transparent margins: find the opaque bounding box.
let minX = png.width;
let minY = png.height;
let maxX = -1;
let maxY = -1;
const colorCounts = new Map();
for (let y = 0; y < png.height; y++) {
  for (let x = 0; x < png.width; x++) {
    const i = (y * png.width + x) * 4;
    const a = png.data[i + 3];
    if (a > 128) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
      const key = `${png.data[i]},${png.data[i + 1]},${png.data[i + 2]}`;
      colorCounts.set(key, (colorCounts.get(key) ?? 0) + 1);
    }
  }
}

const bw = maxX - minX + 1;
const bh = maxY - minY + 1;

// Dominant opaque color becomes the single brand color.
let dominant = [0, 0, 0];
let dominantCount = -1;
for (const [key, count] of colorCounts) {
  if (count > dominantCount) {
    dominantCount = count;
    dominant = key.split(',').map(Number);
  }
}

// Target embedding resolution (width fixed, height preserves aspect ratio).
const TARGET_W = 128;
const TARGET_H = Math.max(1, Math.round((TARGET_W * bh) / bw));

// Build the 1-bit mask via box-filter downsampling (nearest-ish average).
const maskBits = new Uint8Array(TARGET_W * TARGET_H);
for (let ty = 0; ty < TARGET_H; ty++) {
  const y0 = Math.floor((ty * bh) / TARGET_H);
  const y1 = Math.max(y0 + 1, Math.floor(((ty + 1) * bh) / TARGET_H));
  for (let tx = 0; tx < TARGET_W; tx++) {
    const x0 = Math.floor((tx * bw) / TARGET_W);
    const x1 = Math.max(x0 + 1, Math.floor(((tx + 1) * bw) / TARGET_W));
    let opaque = 0;
    let total = 0;
    for (let y = y0; y < y1; y++) {
      for (let x = x0; x < x1; x++) {
        const i = ((minY + y) * png.width + (minX + x)) * 4;
        total++;
        if (png.data[i + 3] > 128) opaque++;
      }
    }
    // Majority-vote threshold so thin strokes survive downsampling.
    maskBits[ty * TARGET_W + tx] = opaque * 2 >= total ? 1 : 0;
  }
}

// Pack MSB-first into bytes.
const bytes = new Uint8Array(Math.ceil((TARGET_W * TARGET_H) / 8));
for (let i = 0; i < TARGET_W * TARGET_H; i++) {
  if (maskBits[i]) bytes[i >> 3] |= 0x80 >> (i & 7);
}
const b64 = Buffer.from(bytes).toString('base64');

const [r, g, b] = dominant;
const ts = `/**
 * Embedded PayNow logo for the QR center overlay.
 *
 * Auto-generated by \`node scripts/generate-paynow-logo.mjs\` from the PayNow
 * brand PNG asset. The logo is a single-color wordmark + "$" glyph on a
 * transparent background, stored as a 1-bit alpha mask (row-major, packed
 * MSB-first into bytes) plus one RGB color — no zlib / PNG decode needed, so
 * it runs in the Workers isolate and in Node identically.
 *
 * Dimensions: ${TARGET_W}x${TARGET_H} (downsampled from a ${bw}x${bh} opaque
 * bounding box), brand color rgb(${r}, ${g}, ${b}).
 */

const LOGO_WIDTH = ${TARGET_W};
const LOGO_HEIGHT = ${TARGET_H};

/** Brand color as [R, G, B]. */
export const LOGO_COLOR: readonly [number, number, number] = [${r}, ${g}, ${b}];

const LOGO_MASK_BASE64 =
  '${b64}';

// Decode the packed mask once at module load (atob is available in both the
// Workers isolate and Node).
const maskBinary = atob(LOGO_MASK_BASE64);
const maskBytes = new Uint8Array(maskBinary.length);
for (let i = 0; i < maskBinary.length; i++) {
  maskBytes[i] = maskBinary.charCodeAt(i);
}

export const logoWidth = LOGO_WIDTH;
export const logoHeight = LOGO_HEIGHT;

/**
 * Whether the logo pixel at (x, y) is opaque (part of the mark).
 * Coordinates are integer, x in [0, logoWidth), y in [0, logoHeight).
 */
export function isLogoOpaque(x: number, y: number): boolean {
  const bit = y * LOGO_WIDTH + x;
  const byte = maskBytes[bit >> 3] ?? 0;
  return ((byte >> (7 - (bit & 7))) & 1) === 1;
}
`;

writeFileSync(new URL('../src/sgqr/paynow-logo.ts', import.meta.url), ts);
console.log(
  `wrote src/sgqr/paynow-logo.ts (${TARGET_W}x${TARGET_H}, rgb(${r},${g},${b}), ${b64.length} b64 chars)`
);
