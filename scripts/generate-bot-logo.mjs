// Generates src/sgqr/bot-logo.ts from the bot logo PNG (web/public/logo.png).
//
// The QR renderer must stay pure JS (no canvas, no PNG decode in the Worker), so the logo is
// area-averaged down to SIZE x SIZE here and stored as raw PREMULTIPLIED RGBA (base64): bilinear
// sampling of premultiplied pixels has no dark fringes at the transparent edge.
//
// Usage: node scripts/generate-bot-logo.mjs [path-to-logo.png]   (default web/public/logo.png)
import { readFileSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';

const SIZE = 96;
const png = PNG.sync.read(readFileSync(process.argv[2] ?? 'web/public/logo.png'));
if (png.width !== png.height) throw new Error('logo must be square');

const out = Buffer.alloc(SIZE * SIZE * 4);
const k = png.width / SIZE;
for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    let r = 0;
    let g = 0;
    let b = 0;
    let a = 0;
    let weight = 0;
    for (let sy = Math.floor(y * k); sy < Math.ceil((y + 1) * k); sy++) {
      for (let sx = Math.floor(x * k); sx < Math.ceil((x + 1) * k); sx++) {
        // fractional overlap of this source pixel with the destination pixel
        const w =
          (Math.min(sx + 1, (x + 1) * k) - Math.max(sx, x * k)) *
          (Math.min(sy + 1, (y + 1) * k) - Math.max(sy, y * k));
        const i = (sy * png.width + sx) * 4;
        const alpha = png.data[i + 3] / 255;
        r += png.data[i] * alpha * w;
        g += png.data[i + 1] * alpha * w;
        b += png.data[i + 2] * alpha * w;
        a += 255 * alpha * w;
        weight += w;
      }
    }
    const o = (y * SIZE + x) * 4;
    out[o] = Math.round(r / weight);
    out[o + 1] = Math.round(g / weight);
    out[o + 2] = Math.round(b / weight);
    out[o + 3] = Math.round(a / weight);
  }
}

writeFileSync(
  'src/sgqr/bot-logo.ts',
  `/**
 * Embedded bot logo for the QR center overlay.
 *
 * Auto-generated by \`node scripts/generate-bot-logo.mjs\` from web/public/logo.png: ${SIZE}x${SIZE}
 * premultiplied RGBA, base64. Plain base64 (no zlib), so it decodes the same in the Workers
 * isolate and in Node.
 */

export const BOT_LOGO_SIZE = ${SIZE};

const BOT_LOGO_BASE64 =
  '${out.toString('base64')}';

/** Premultiplied RGBA, row-major, BOT_LOGO_SIZE * BOT_LOGO_SIZE * 4 bytes. */
export const BOT_LOGO_RGBA: Uint8Array = Uint8Array.from(atob(BOT_LOGO_BASE64), (c) =>
  c.charCodeAt(0)
);
`
);
console.log('wrote src/sgqr/bot-logo.ts', out.length, 'bytes raw');
