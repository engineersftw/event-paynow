const TABLE: number[][] = GLYPHS.replace(/\s+/g, '')
  .match(/.{10}/g)!
  .map((g) => g.match(/.{2}/g)!.map((b) => Number.parseInt(b, 16)));

/** Glyph columns for a char; anything outside printable ASCII falls back to '?'. */
export function glyph(ch: string): readonly number[] {
  const code = ch.charCodeAt(0);
  return TABLE[code >= 0x20 && code <= 0x7e ? code - 0x20 : 0x3f - 0x20]!;
}

export const GLYPH_COUNT = TABLE.length;
